/**
 * Universal Cross-IDE Rules Transpiler (`immune compile-rules`).
 *
 * Compiles proven, share-safe SQLite pitfall antibodies into native IDE rule
 * formats across Cursor (`.cursor/rules/immune-pitfalls.mdc` with automatic
 * file-glob inference), GitHub Copilot (`.github/copilot-instructions.md`),
 * Windsurf (`.windsurfrules`), Cline (`.clinerules`), and Claude/Codex (`CLAUDE.md`).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { isTeamShareSafe, type TeamSyncCandidate } from './team-sync.js';

export type IdeRuleTarget = 'cursor' | 'copilot' | 'windsurf' | 'cline' | 'claude';

export const IDE_TARGET_PATHS: Record<IdeRuleTarget, string> = {
  cursor: '.cursor/rules/immune-pitfalls.mdc',
  copilot: '.github/copilot-instructions.md',
  windsurf: '.windsurfrules',
  cline: '.clinerules',
  claude: 'CLAUDE.md',
};

export interface CompiledIdeFile {
  readonly target: IdeRuleTarget;
  readonly relativePath: string;
  readonly fullPath: string;
  readonly rulesCount: number;
  readonly content: string;
}

const START_MARKER = '<!-- immune:generated:start -->';
const END_MARKER = '<!-- immune:generated:end -->';

/** Automatically infer file globs from a rule's trigger, symptom, and prescription. */
export function inferRuleGlobs(rule: TeamSyncCandidate): string {
  const text = `${rule.trigger_pattern} ${rule.symptom} ${rule.prescription}`.toLowerCase();
  if (/(?:cargo|rustc|e0502|borrow|tokio|\.rs\b)/.test(text)) return '**/*.rs, **/Cargo.toml';
  if (/(?:go\.mod|go test|goroutine|\.go\b)/.test(text)) return '**/*.go, **/go.mod';
  if (/(?:pytest|uv |pip |pyproject\.toml|requirements\.txt|\.py\b)/.test(text)) {
    return '**/*.py, **/pyproject.toml';
  }
  if (/(?:dockerfile|docker-compose|\.dockerignore|container)/.test(text)) {
    return '**/Dockerfile*, **/docker-compose*.yml';
  }
  if (/(?:next\/|tsx|jsx|tailwind|react|vite\.config)/.test(text)) {
    return '**/*.tsx, **/*.ts, **/*.jsx';
  }
  if (/(?:tsconfig|package\.json|pnpm|nodenext|\.ts\b)/.test(text)) {
    return '**/*.ts, **/*.js, **/package.json';
  }
  return '*';
}

/** Filter and sort share-safe rules eligible for IDE compilation. */
export function selectCompilableRules(
  candidates: ReadonlyArray<TeamSyncCandidate>,
  minHits = 1,
): TeamSyncCandidate[] {
  return candidates
    .filter((r) => (!r.status || r.status === 'active') && (r.hit_count ?? 1) >= minHits && isTeamShareSafe(r))
    .sort((a, b) => (b.hit_count ?? 1) - (a.hit_count ?? 1));
}

/** Render a fenced Markdown block for Copilot, Windsurf, Cline, or Claude. */
export function renderFencedRuleBlock(
  target: IdeRuleTarget,
  rules: ReadonlyArray<TeamSyncCandidate>,
): string {
  const lines: string[] = [
    START_MARKER,
    `## 🛡️ Agent Immune — Learned Repository Pitfall Rules (${target})`,
    '',
    '> Auto-compiled by `npx dsh-immune-system compile-rules`. Edit outside the `immune:generated` markers.',
    '',
  ];

  if (rules.length === 0) {
    lines.push('- *(No share-safe rules met the minimum hit threshold yet.)*');
  } else {
    for (const r of rules) {
      const globs = inferRuleGlobs(r);
      const toolTag = r.tool_name ? `[${r.tool_name}] ` : '';
      lines.push(
        `- **${toolTag}When**: \`${r.trigger_pattern.trim()}\` *(files: \`${globs}\`)*`,
        `  - **Avoid**: ${r.symptom.trim()}`,
        `  - **Do instead**: ${r.prescription.trim()}`,
      );
    }
  }

  lines.push('', END_MARKER);
  return lines.join('\n');
}

/** Render a Cursor `.mdc` rule file with YAML frontmatter and per-rule glob hints. */
export function renderCursorMdc(rules: ReadonlyArray<TeamSyncCandidate>): string {
  const uniqueGlobs = new Set<string>();
  for (const r of rules) {
    for (const g of inferRuleGlobs(r).split(',').map((s) => s.trim())) {
      if (g && g !== '*') uniqueGlobs.add(g);
    }
  }
  const globHeader = uniqueGlobs.size > 0 ? [...uniqueGlobs].slice(0, 8).join(', ') : '*';

  const lines: string[] = [
    '---',
    'description: Auto-compiled coding agent pitfall immunity rules (dsh-immune-system)',
    `globs: ${globHeader}`,
    'alwaysApply: true',
    '---',
    '',
    '# 🛡️ Agent Immune — Learned Pitfall Rules',
    '',
    '> Auto-generated by `npx dsh-immune-system compile-rules --target cursor`.',
    '',
  ];

  for (const r of rules) {
    const globs = inferRuleGlobs(r);
    const toolTag = r.tool_name ? `[${r.tool_name}] ` : '';
    lines.push(
      `- **${toolTag}Trigger**: \`${r.trigger_pattern.trim()}\` *(applies to: \`${globs}\`)*`,
      `  - **Avoid**: ${r.symptom.trim()}`,
      `  - **Prescription**: ${r.prescription.trim()}`,
    );
  }

  lines.push('');
  return lines.join('\n');
}

/** Merge a fenced block into an existing Markdown file without clobbering user content. */
export function mergeFencedContent(existingRaw: string, fencedBlock: string): string {
  const startIdx = existingRaw.indexOf(START_MARKER);
  const endIdx = existingRaw.indexOf(END_MARKER);
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const before = existingRaw.slice(0, startIdx).trimEnd();
    const after = existingRaw.slice(endIdx + END_MARKER.length).trimStart();
    return [before, fencedBlock, after].filter(Boolean).join('\n\n') + '\n';
  }
  const trimmed = existingRaw.trimEnd();
  return trimmed ? `${trimmed}\n\n${fencedBlock}\n` : `${fencedBlock}\n`;
}

/**
 * Compile and optionally write IDE rule files for one or more targets.
 */
export function compileIdeRules(
  workspace: string,
  candidates: ReadonlyArray<TeamSyncCandidate>,
  opts: {
    targets?: ReadonlyArray<IdeRuleTarget>;
    minHits?: number;
    dryRun?: boolean;
  } = {},
): CompiledIdeFile[] {
  const targets: ReadonlyArray<IdeRuleTarget> =
    opts.targets && opts.targets.length > 0
      ? opts.targets
      : ['cursor', 'copilot', 'windsurf', 'cline', 'claude'];
  const rules = selectCompilableRules(candidates, opts.minHits ?? 1);
  const out: CompiledIdeFile[] = [];

  for (const target of targets) {
    const relativePath = IDE_TARGET_PATHS[target];
    const fullPath = join(workspace, relativePath);
    let content: string;
    if (target === 'cursor') {
      content = renderCursorMdc(rules);
    } else {
      const fenced = renderFencedRuleBlock(target, rules);
      const existing = existsSync(fullPath) ? readFileSync(fullPath, 'utf8') : '';
      content = mergeFencedContent(existing, fenced);
    }
    if (!opts.dryRun) {
      mkdirSync(dirname(fullPath), { recursive: true });
      writeFileSync(fullPath, content, 'utf8');
    }
    out.push({
      target,
      relativePath,
      fullPath,
      rulesCount: rules.length,
      content,
    });
  }

  return out;
}
